do $$
declare t text;
begin
  foreach t in array array['inverters','provider_accounts','provider_devices','provider_sessions','raw_provider_payloads','telemetry_samples','energy_counters','alarms','device_settings','variable_mappings','sync_runs','credential_audit_events'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on public.%I from anon,authenticated',t);
  end loop;
end $$;

