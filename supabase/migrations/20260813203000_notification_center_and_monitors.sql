-- Una instalación de la PWA representa al mismo propietario y recibe avisos de
-- todas sus casas. Replica las suscripciones existentes a cada sitio registrado.
insert into public.push_subscriptions (site_id, endpoint, p256dh, auth, failure_count)
select sites.id, subscriptions.endpoint, subscriptions.p256dh, subscriptions.auth, 0
from public.solar_sites sites
cross join (select distinct on (endpoint) endpoint, p256dh, auth from public.push_subscriptions order by endpoint, created_at desc) subscriptions
on conflict (site_id, endpoint) do update
set p256dh = excluded.p256dh, auth = excluded.auth, failure_count = 0;
