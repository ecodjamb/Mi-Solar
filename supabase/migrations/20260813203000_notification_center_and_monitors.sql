alter table public.automation_rules
  add column if not exists notification_preferences jsonb not null default jsonb_build_object(
    'automationExecuted', true,
    'automationState', true,
    'serviceOutage', true,
    'solarSurplus', true
  );

create table if not exists public.notification_events (
  id bigint generated by default as identity primary key,
  site_id bigint not null references public.solar_sites(id) on delete cascade,
  event_type text not null check (event_type in ('automation_executed','automation_state','service_outage','service_recovery','solar_surplus','test')),
  title text not null,
  body text not null,
  dedupe_key text,
  delivered_count integer not null default 0 check (delivered_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  created_at timestamptz not null default now()
);

create unique index if not exists notification_events_dedupe_idx
  on public.notification_events (site_id, dedupe_key)
  where dedupe_key is not null;
create index if not exists notification_events_site_created_idx
  on public.notification_events (site_id, created_at desc);

create table if not exists public.notification_states (
  site_id bigint not null references public.solar_sites(id) on delete cascade,
  event_key text not null,
  state text not null,
  metadata jsonb not null default '{}'::jsonb,
  last_notified_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (site_id, event_key)
);

alter table public.notification_events enable row level security;
alter table public.notification_states enable row level security;

revoke all on public.notification_events, public.notification_states from public, anon, authenticated;
grant select, insert on public.notification_events to anon;
grant select, insert, update on public.notification_states to anon;
grant usage, select on sequence public.notification_events_id_seq to anon;

