      'Authorization', 'Bearer ' || coalesce((select decrypted_secret from vault.decrypted_secrets where name = 'misolar_cron_secret' limit 1), '')
    ),
    body := jsonb_build_object('scheduled_at', now()),
    timeout_milliseconds := 55000
  ) as request_id;
  $job$
